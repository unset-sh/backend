// Writes api/internal/app.d.ts, the internal API's type for Eden Treaty in web (org-0017), from scripts/app-type.ts,
// or with --check fails when the committed file differs, so a route change without its type cannot pass
// `bun run check`. tsc writes the declaration to a temporary folder; only the one file is kept. TypeScript 7.0.2's
// package exports no compiler API (its "." entry is lib/version.cjs), so the binary runs instead.
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

export const TYPES_PATH = new URL("../api/internal/app.d.ts", import.meta.url);
const ROOT = new URL("..", import.meta.url).pathname;

/** The installed elysia version: the exact peer a consumer of the type must run. */
export function elysiaVersion(): string {
  const manifest = JSON.parse(readFileSync(join(ROOT, "node_modules/elysia/package.json"), "utf8")) as {
    version: string;
  };
  return manifest.version;
}

/** The declaration text, with a header naming the elysia version it was written against. */
export function appTypes(): string {
  const out = mkdtempSync(join(tmpdir(), "app-types-"));
  try {
    const tsc = Bun.spawnSync(
      [join(ROOT, "node_modules/.bin/tsc"), "-p", join(ROOT, "tsconfig.app-types.json"), "--outDir", out],
      { cwd: ROOT, stdout: "pipe", stderr: "pipe" },
    );
    if (tsc.exitCode !== 0) throw new Error(`tsc failed:\n${tsc.stdout.toString()}${tsc.stderr.toString()}`);
    const emitted = readFileSync(join(out, "scripts/app-type.d.ts"), "utf8");
    return [
      "// Generated by `bun scripts/app-types.ts` from backend's route schemas; do not edit.",
      `// The internal API's type for Eden Treaty (org-0017). It holds for elysia ${elysiaVersion()} exactly.`,
      emitted,
    ].join("\n");
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
}

if (import.meta.main) {
  const text = appTypes();
  if (process.argv.includes("--check")) {
    const committed = readFileSync(TYPES_PATH, "utf8");
    if (committed !== text) {
      process.stderr.write("api/internal/app.d.ts is out of date: run `bun scripts/app-types.ts`.\n");
      process.exit(1);
    }
  } else {
    writeFileSync(TYPES_PATH, text);
  }
}
